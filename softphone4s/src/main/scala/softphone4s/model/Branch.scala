package softphone4s.model

import cats.{Eq, Show}

/** The `branch` parameter of a Via header, identifying a transaction. */
opaque type Branch = String

object Branch {
  private val MagicCookie = "z9hG4bK"
  private val syntax = UriSyntax.token(UriSyntax.TokenChars, nonEmpty = true)

  def apply(s: String): Either[String, Branch] =
    UriSyntax.check("branch", syntax, s)

  /** A branch of random bytes in hex, with the RFC 3261 magic cookie. */
  def fromBytes(bytes: Array[Byte]): Branch = MagicCookie + UriSyntax.hex(bytes)

  extension (b: Branch) {
    def value: String = b

    /** Whether the branch was generated by an RFC 3261 compliant element and so
      * is globally unique (§8.1.1.7).
      */
    def isRfc3261: Boolean = b.startsWith(MagicCookie)
  }

  given Eq[Branch]   = Eq.fromUniversalEquals
  given Show[Branch] = Show.show(identity)
}
